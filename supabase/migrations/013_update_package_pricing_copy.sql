-- 013: อัปเดตข้อความส่วนลดให้ตรงกับราคาแพ็กเล็กปัจจุบัน (49 บาท)
--
-- ตอนขึ้นราคาแพ็ก 1,000 หัวใจ จาก 40 → 49 ข้อความ "ประหยัดกว่า N%"
-- ไม่ได้อัปตาม ตัวเลขเดิม (14% / 18%) คิดจากฐาน 40 บาท
--
--   ฐาน 49 บาท = 0.0490 บาท/หัวใจ
--   2,000 หัวใจ 69 บาท = 0.0345 บาท/หัวใจ → ถูกกว่า 29.6% ≈ 30%
--   3,000 หัวใจ 99 บาท = 0.0330 บาท/หัวใจ → ถูกกว่า 32.7% ≈ 33%

UPDATE public.packages
SET description = 'คุ้มค่าที่สุด ประหยัดกว่า 30%'
WHERE slug = '2000-hearts';

UPDATE public.packages
SET description = 'สำหรับสายฟาร์มจริงจัง ประหยัดกว่า 33%'
WHERE slug = '3000-hearts';
